const assert=require('node:assert/strict');
const {makeCtx}=require('./dom');
const {run}=makeCtx({setTimeout:()=>0});
run(`DB.load();DB.seedDemo();AUTH.user={id:'synthetic-exporter',username:'synthetic.exporter',name:'Synthetic <Exporter>',roleId:'mcm',countyId:'kisumu'};`);
const provenance=JSON.parse(run('JSON.stringify(reportProvenance())'));
assert.equal(provenance.department,'Medical & Clinical Services');
assert.equal(provenance.name,'Synthetic <Exporter>');
const stamp=run('reportProvenanceHTML()');assert(stamp.includes('Synthetic &lt;Exporter&gt;'));assert(!stamp.includes('<Exporter>'));
const shell=run(`reportShell({title:'Synthetic report',sub:'Synthetic',meta:[],body:'<p>Recorded result</p>'})`);
assert(shell.includes('Department:'));assert(shell.includes('Medical &amp; Clinical Services'));assert(shell.includes('synthetic.exporter'));
run(`globalThis.__layout={fields:Object.fromEntries(CARE_RULES.FIELDS.map(([k])=>[k,'Recorded '+k])),report:{id:'synthetic-report',version:1},patient_code:'SYN-1',report_title:'Synthetic PDCA',cycleId:'synthetic-cycle',status:'draft',mode:'120day'};`);
const html=run('CARE_REVIEW.template(__layout)');
assert.equal((html.match(/class="care-template-page"/g)||[]).length,2);
assert.equal((html.match(/class="care-template-columns"><div><\/div>/g)||[]).length,0);
for(const key of JSON.parse(run('JSON.stringify(CARE_RULES.FIELDS.map(([k])=>k))')))assert(html.includes('Recorded '+key),key);
assert.equal((html.match(/data-report-provenance="Generated"/g)||[]).length,2);
for(const label of ['01 PLAN','02 DO','03 CHECK','04 ACT'])assert(html.includes(label));
const word=Buffer.from(run('CARE_REVIEW.wordBytes(__layout)')).toString('utf8');
assert(word.includes('Department: Medical &amp; Clinical Services'));assert(word.includes('synthetic.exporter'));
const xlsx=Buffer.from(run(`XLSX.fromSheets([{name:'Results',rows:[['Result'],['Synthetic']]}],'Synthetic report')`)).toString('utf8');
assert(xlsx.includes('Report provenance'));assert(xlsx.includes('Medical &amp; Clinical Services'));assert(xlsx.includes('synthetic.exporter'));
console.log('Report layout/provenance: balanced spreads, all source fields, escaped user/department, PDCA graphics and Word/spreadsheet attribution passed.');
