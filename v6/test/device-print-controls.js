/* Synthetic-only checks; no printer, camera or production account is accessed. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {makeCtx}=require('./dom');
const {run,ctx}=makeCtx();
const snapshot=(navigator,width)=>JSON.parse(run(`JSON.stringify(CLIENT_UI.snapshot(${JSON.stringify({navigator,width,height:900})}))`));
assert.equal(snapshot({userAgent:'Mozilla Android 14 Mobile Chrome/130'},412).type,'phone');
assert.equal(snapshot({userAgent:'Mozilla Android 14 Chrome/130'},1024).type,'tablet');
assert.equal(snapshot({userAgent:'Macintosh Safari/17',platform:'MacIntel',maxTouchPoints:5},1024).type,'tablet');
assert.equal(snapshot({userAgent:'Windows NT Chrome/130'},1440).platform,'Windows');
assert.equal(snapshot({userAgent:'Windows NT Chrome/130'},540).layout,'compact');
assert.equal(snapshot({userAgent:'Windows NT Chrome/130'},1400).layout,'wide');
run('DB.load();DB.seedDemo();');
const originalQuery=ctx.document.querySelector.bind(ctx.document);
ctx.document.querySelector=s=>s==='#content .report-doc'?null:originalQuery(s);
run('PRINT_CONTROL.open("workspace")');
assert.ok(ctx.document.querySelector('#root'));
assert.equal(run('typeof FORMS["print-settings"]'),'function');
assert.equal(run('typeof ACTIONS["do-print"]'),'function');
let printed=0,settings=null;
const modes=new Set(),events={};
ctx.document.getElementById=()=>settings;
ctx.document.head={appendChild(node){settings=node;}};
ctx.document.body.classList={add:x=>modes.add(x),remove:x=>modes.delete(x)};
ctx.window.addEventListener=(event,fn)=>{events[event]=fn;};
ctx.window.removeEventListener=(event,fn)=>{if(events[event]===fn)delete events[event];};
ctx.window.print=()=>{printed++;};
run('PRINT_CONTROL.execute("A4","landscape")');
assert.equal(printed,1);
assert.match(settings.textContent,/size:A4 landscape/);
assert.ok(modes.has('print-workspace'),'print mode stays active until the dialog finishes');
events.afterprint();assert.ok(!modes.has('print-workspace'));assert.equal(events.focus,undefined,'paired focus listener is removed after printing');
run('PRINT_CONTROL.execute("<script>","portrait")');assert.equal(printed,1,'invalid page settings do not reach CSS or printing');
const source=fs.readFileSync('v6/src/office_actions.js','utf8');
assert.ok(source.includes("window.addEventListener('afterprint',clean,{once:true})"));
assert.ok(!source.includes('setTimeout(done,800)'),'printing must not hide the document during a still-open print preview');
assert.ok(source.includes("['A4','Letter'].includes(size)"));
const header=JSON.parse(fs.readFileSync('vercel.json')).headers.flatMap(h=>h.headers).find(h=>h.key==='Permissions-Policy').value;
assert.ok(header.includes('camera=(self)')&&header.includes('microphone=(self)'));
assert.ok(fs.readFileSync('src/App.tsx','utf8').includes('allow="camera; microphone;'));
assert.equal(run('MAJOR_DEPARTMENTS.length'),11);
assert.deepEqual(JSON.parse(run('JSON.stringify(MAJOR_DEPARTMENTS.slice(0,8).map(d=>d.name))')),['Administration','Field Care','Hospital','Transport','Media & IT','Homestay','Procurement','Finance']);
console.log('Device / print controls: client hints, compact windows, platform detection, print lifecycle, policy delegation and 11-department structure passed.');
