const assert=require('node:assert/strict');
const {makeCtx}=require('./dom');
const {run}=makeCtx({setTimeout:()=>0});
run(`DB.load();DB.seedDemo();globalThis.__originalHas=RBAC.has;globalThis.__originalList=repo.patientList;
 globalThis.__auditUser={id:'synthetic-auditor',roleId:'countyadmin',countyId:'kisumu'};
 RBAC.has=(u,c)=>['dq.manage','patient.view.clinical','form.view','finance.view'].includes(c);
 repo.patientList=()=>[{id:'synthetic-p',countyId:'kisumu'},{id:'synthetic-other',countyId:'kisumu'}];
 DB.db.formRecords=[{id:'synthetic-form',kind:'home_visit',status:'verified',patientId:'synthetic-p',enteredBy:'synthetic-field',data:{visitDate:'2026-11-24',weightKg:'50'}}];
 DB.db.visits=[{id:'synthetic-visit',patientId:'synthetic-p',date:'2026-11-24',by:'synthetic-clinical',weightKg:52}];
 DB.db.requests=[{id:'synthetic-request',patientId:'synthetic-p',requestedBy:'synthetic-field',status:'closed'}];
 DB.db.transactions=[{id:'synthetic-tx',patientId:'synthetic-other',countyId:'kisumu',requestId:'synthetic-request',enteredBy:'synthetic-finance',status:'paid'}];`);
const findings=()=>JSON.parse(run('JSON.stringify(DQ6.crossAccountFindings(__auditUser))'));
const before=run('JSON.stringify([DB.db.visits,DB.db.formRecords,DB.db.requests,DB.db.transactions])');
assert(findings().some(i=>i.rule==='cross-account-weight'));
assert(findings().some(i=>i.rule==='cross-account-patient-link'&&i.level==='block'));
assert(findings().some(i=>i.rule==='cross-account-review-gap'));
assert.equal(before,run('JSON.stringify([DB.db.visits,DB.db.formRecords,DB.db.requests,DB.db.transactions])'));
run('DB.db.visits.push({...DB.db.visits[0],id:"synthetic-second-observation"})');
assert(!findings().some(i=>i.rule==='cross-account-weight'),'ambiguous same-day observations must not be paired');
run('DB.db.visits.pop();DB.db.formRecords[0].status="draft"');assert(!findings().some(i=>i.rule==='cross-account-weight'));
run('DB.db.formRecords[0].status="verified";DB.db.visits[0].by="synthetic-field"');assert(!findings().some(i=>i.rule==='cross-account-weight'));
run('DB.db.visits[0].by="synthetic-clinical";DB.db.transactions[0].countyId="homabay"');
assert(!findings().some(i=>i.category.includes('finance')),'county-out-of-scope financial evidence excluded');
run('repo.patientList=()=>[]');assert.deepEqual(findings(),[]);
run('repo.patientList=__originalList;RBAC.has=()=>false');assert.deepEqual(findings(),[]);
console.log('Cross-account audit: category rules, source/account attribution, no source mutation, same-account/draft/ambiguity exclusions and patient/county/capability boundaries passed.');
