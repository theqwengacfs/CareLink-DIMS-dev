const assert=require('node:assert/strict');
const {makeCtx}=require('./dom');
const {run}=makeCtx();
run('DB.load(); DB.seedDemo();');
run(`AUTH.user=DB.db.users.find(u=>u.roleId==='caregiver'); DB.db.personalPrefs[AUTH.user.id]={homeLayoutMode:'smart'};`);
const render=cards=>run(`WORKSPACE_LAYOUTS.renderHomeWorkspace(AUTH.user,{omitHeader:true,arranged:${JSON.stringify(cards)}})`);
const card=n=>`<div class="card"><h3>Sample module ${n}</h3></div>`;
let html=render([card(1),card(2),card(3),card(4)]);
assert(/<details class="ws67-secondary-drawer ws67-more-workspaces"[^>]*>/.test(html));
assert(!/<details class="ws67-secondary-drawer ws67-more-workspaces"[^>]*\bopen\b/.test(html));
for(let i=1;i<=4;i++)assert(html.includes('Sample module '+i));
run('WORKSPACE_LAYOUTS._moreOpen={[AUTH.user.id]:true}');
html=render([card(1),card(2),card(3)]);assert(/data-workspace-more="[^"]+" open/.test(html));
run('WORKSPACE_LAYOUTS._moreOpen={}');
html=render([card(1),card(2),'<div class="card"><h3>Attention</h3><div class="alert crit">Critical item</div></div>']);
assert(/data-workspace-more="[^"]+" open/.test(html));assert(html.includes('Attention flagged'));
run(`DB.db.personalPrefs[AUTH.user.id].homeLayoutMode='full'`);
html=render([card(1),card(2),card(3)]);assert(!html.includes('data-workspace-more'));assert(html.includes('Sample module 3'));
run(`DB.db.personalPrefs[AUTH.user.id].homeLayoutMode='tabbed'`);
html=render([card(1),card(2),card(3)]);assert(html.includes('ws67-tabbed-deck'));assert(!html.includes('data-workspace-more'));
const hero=run(`WORKSPACE_LAYOUTS.renderHomeHero(AUTH.user,{greeting:'Welcome',currentView:'home',actionsHtml:'<button>Primary action</button>'})`);
assert(hero.includes('Primary action'));assert(hero.includes('ws67-workspace-tools'));assert(hero.includes('Workspace tools'));assert(hero.includes('ws67-layout-options'));
const inner=run(`WORKSPACE_LAYOUTS.renderHomeHero(AUTH.user,{greeting:'Welcome',currentView:'patient'})`);
assert(!inner.includes('ws67-layout-options'));
console.log('Workspace disclosure tests passed: module retention, saved open state, critical auto-expansion, layout modes and primary actions.');
