/* ============================================================================
   report-period-labels.js — every document states the period it actually covers.

   The Foundation's planning year is a 52-week year of Monday-Friday working
   days, and the Monday meeting reads "week 48 of 2026, Monday 16 - Friday 20".
   A weekly report that still prints "7 days to 26 Nov 2026" cannot be
   reconciled against that planning year, and a monthly expenditure report that
   borrows the weekly label overstates its own period.

   This suite pins the mapping: which report families are weekly, which are
   monthly, which are quarterly, and that every printed document names the
   department that issued it (the usage-trial report asks for this, and a
   document without a named owner is not auditable).
   ============================================================================ */
const assert = require('node:assert/strict');
const { makeCtx } = require('./dom');

let passed = 0;
function check(name, condition, detail) {
  assert.ok(condition, name + (detail === undefined ? '' : ` — ${detail}`));
  passed++;
  console.log(`  ok  ${name}`);
}

const { run } = makeCtx();
run('DB.load();');
run('DB.seedDemo();');

const weeklyLabel = () => run('PERIOD.lastCompletedWorkWeek().label');
const docMeta = (type, roleId = 'director') => {
  const html = run(`buildReportDoc('${type}',{countyId:'all'},DB.db.users.find(u=>u.roleId==='${roleId}'))`);
  const meta = html.match(/<div class="meta-grid">([\s\S]*?)<\/div>\s*<div class="rpt-body-flow">/);
  const text = (meta ? meta[1] : '').replace(/<[^>]+>/g, ' | ');
  const period = (text.match(/Reporting period \| ([^|]*)/) || [])[1] || '';
  const by = (text.match(/Generated by \| ([^|]*)/) || [])[1] || '';
  return { period: period.trim(), by: by.trim(), html };
};

/* ---- the work-week label itself ---------------------------------------- */
const label = weeklyLabel();
check('the work-week label names the week number and the year',
  /^Week \d{1,2} of \d{4}/.test(label), label);
check('the work-week label gives the Monday-to-Friday span, not a 7-day rolling window',
  /Monday \d{1,2} \w{3} \d{4} – Friday \d{1,2} \w{3} \d{4}/.test(label), label);
check('the work-week label names the working timezone',
  /Africa\/Nairobi/.test(label), label);
check('the work-week label never exceeds week 52, because the planning year is a 52-week year',
  (() => {
    let worst = 0;
    for (let d = 0; d < 800; d++) {
      const day = new Date(Date.UTC(2026, 0, 1) + d * 86400000).toISOString().slice(0, 10);
      const w = run(`PERIOD.workWeek('${day}').planningWeek`);
      if (w > worst) worst = w;
    }
    return worst <= 52;
  })(), 'week number above 52');
check('two different planning weeks never share a label',
  (() => {
    const seen = new Set();
    for (let d = 0; d < 400; d++) {
      const day = new Date(Date.UTC(2026, 0, 1) + d * 86400000).toISOString().slice(0, 10);
      seen.add(run(`PERIOD.workWeek('${day}').label`));
    }
    return seen.size > 50;
  })());
check('the working week starts on Monday and ends on Friday',
  run(`(()=>{ const p=PERIOD.workWeek('2026-11-25');
    return new Date(p.civilStart+'T00:00:00Z').getUTCDay()===1 && new Date(p.civilEnd+'T00:00:00Z').getUTCDay()===5; })()`));

/* ---- every report family prints the period it actually covers ---------- */
for (const type of ['weekly_indicators', 'patient_figures', 'patient_days', 'home_visits']) {
  const { period, html } = docMeta(type);
  check(`the ${type} document prints the work-week label`, period === label, period);
  check(`the ${type} document no longer says "7 days to"`, !/7 days to/.test(html));
}
/* The referral document is restricted to the MCM and authorised roles, so it is
   read as that account; the others are read as leadership. */
for (const [type, roleId] of [['expenditure', 'director'], ['quality', 'director'], ['referral', 'mcm']]) {
  const { period } = docMeta(type, roleId);
  check(`the ${type} document is filed by month, not by week`,
    /^[\w]+ \d{4}$/.test(period) && !/Week \d/.test(period), period);
}
for (const type of ['executive', 'donor']) {
  const { period } = docMeta(type);
  check(`the ${type} document is filed by quarter`, /^Q[1-4] \d{4}$/.test(period), period);
}
check('no printed document still uses the rolling 7-day window',
  ['weekly_indicators', 'patient_figures', 'patient_days', 'home_visits', 'expenditure',
    'quality', 'executive', 'donor', 'condition_summary']
    .every(t => !/7 days to/.test(docMeta(t).html)));

/* ---- the issuing department is on the document ------------------------- */
const clinical = docMeta('patient_figures', 'mcm');
check('the document names the person who generated it', /Medical Case Manager/.test(clinical.by), clinical.by);
/* The meta grid escapes its values, so the department label is read with &amp;. */
check('the document names the issuing department, taken from the org chart',
  /Medical &(amp;|amp;amp;)?\s*Clinical Services/.test(clinical.by), clinical.by);
check('a leadership document names the leadership department',
  /Executive Leadership/.test(docMeta('executive', 'director').by), docMeta('executive', 'director').by);
check('the department label is escaped, not injected as markup',
  !/<(?!\/?(div|span|b|table|thead|tbody|tr|td|th|p|h2|h4|img)\b)/.test(clinical.by));
/* The referral document is refused outright to an account without the referral
   capability, and that refusal is itself the correct behaviour, not a gap. */
const catalogue = JSON.parse(run(`JSON.stringify(REPORTS.types().map(t => {
  const html = buildReportDoc(t.type, {countyId:'all'}, DB.db.users.find(u=>u.roleId==='chief'));
  return { type:t.type, period:/Reporting period/.test(html), by:/Generated by/.test(html),
    refused:/Not authorised/.test(html) };
}))`));
const unexplained = catalogue.filter(r => !r.refused && !(r.period && r.by));
check('every report the account may read carries a period and a named generator',
  unexplained.length === 0, JSON.stringify(unexplained));
check('the one refused document is refused explicitly, not rendered blank',
  catalogue.filter(r => r.refused).length <= 1);

console.log(`report-period-labels: ${passed} checks passed`);
