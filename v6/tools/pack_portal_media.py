#!/usr/bin/env python3
"""Optimise and bundle the LOMAMO public-portal programme photography.

The portal photographs are programme imagery generated for this repository:
no identifiable beneficiary appears in any of them, because publishing a
patient photograph needs recorded consent under the LOMAMO Ethical
Storytelling Policy.

Inputs  : public/media/<key>.jpg
Outputs : v6/src/media_portal.js   (base64, for the offline single file)
          public/media/<key>.jpg   (optimised, for hosted delivery)
          v6/assets/media/<key>.jpg

Run:  python3 v6/tools/pack_portal_media.py
"""
import base64
import json
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
PUBLIC = ROOT / "public" / "media"
ASSETS = ROOT / "v6" / "assets" / "media"
OUT_JS = ROOT / "v6" / "src" / "media_portal.js"

WIDTH = 760
QUALITY = 62
MAX_KB = 62

ITEMS = [
    ("field_home_visit", "A weekly home visit", "Ministry & Field Programmes",
     "Clinical review, nutrition and encouragement at the household door."),
    ("foodbag_nutrition", "Nutritious food for the week", "Procurement & Nutrition",
     "Bag 1, Bag 2 and the Special bag, issued against the household's need."),
    ("hospital_escort", "Escort to hospital", "Hospital Coordination",
     "Friday hospital visits with transport and an escort."),
    ("tb_adherence", "TB adherence support", "Pharmacy & Medical",
     "Pyridoxine with every anti-TB course, on a ten-day cycle."),
    ("children_school", "Children kept in school", "Education & Orphan Prevention",
     "Uniforms, books and fees so a crisis does not become a lost future."),
    ("chv_meeting", "Community health volunteers", "Community Partnerships",
     "The volunteers and CHWs who tell us which household is in danger."),
    ("lake_kisumu", "Kisumu, on Lake Victoria", "Where we serve",
     "Urban slums and remote villages across Kisumu and Homa Bay."),
    ("monday_meeting", "Monday management meeting", "Administration",
     "Everyone at the office on Monday, except sick leave and the hospital ministry."),
    ("stock_room", "Stock counted and reconciled", "Procurement & Pharmacy",
     "Every tablet accounted for against what was procured."),
    ("field_transport", "Field transport", "Vehicle & Transport",
     "Drivers who can reach a village as well as a referral hospital."),
]


def optimise(path: Path) -> tuple[Image.Image, int]:
    im = Image.open(path).convert("RGB")
    w, h = im.size
    if w > WIDTH:
        im = im.resize((WIDTH, round(h * WIDTH / w)), Image.LANCZOS)
    q = QUALITY
    im.save(path, "JPEG", quality=q, optimize=True, progressive=True)
    while path.stat().st_size > MAX_KB * 1024 and q > 42:
        q -= 4
        im.save(path, "JPEG", quality=q, optimize=True, progressive=True)
    return im, q


def main() -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    photos, meta = {}, {}
    for key, label, dept, caption in ITEMS:
        src = PUBLIC / f"{key}.jpg"
        if not src.exists():
            print(f"  ! missing {src}")
            continue
        im, q = optimise(src)
        shutil.copyfile(src, ASSETS / f"{key}.jpg")
        data = src.read_bytes()
        photos[key] = "data:image/jpeg;base64," + base64.b64encode(data).decode()
        meta[key] = {
            "label": label, "dept": dept, "caption": caption,
            "w": im.size[0], "h": im.size[1],
            "kb": round(len(data) / 1024, 1), "quality": q,
        }
        print(f"  · {key}: {im.size[0]}x{im.size[1]} {meta[key]['kb']} KB q{q}")

    js = """/* ============================================================
   media_portal.js - LOMAMO public-portal programme photography
   ------------------------------------------------------------
   Generated by v6/tools/pack_portal_media.py. Do not edit by hand.

   These ten images carry the programme context of the Foundation's
   public pages: the weekly home visit, the food bag, the escort to
   hospital, TB adherence support, children kept in school, the
   community health volunteers, Kisumu on Lake Victoria, the Monday
   management meeting, the counted stock room and field transport.

   No identifiable beneficiary appears in any of them. Publishing a
   patient photograph requires recorded consent under the LOMAMO
   Ethical Storytelling Policy, so the portal uses programme imagery
   that carries the context without exposing a person in care.
   ============================================================ */

const CARELINK_PORTAL_PHOTOS = {
%s
};

const CARELINK_PORTAL_PHOTO_META = {
%s
};

/* One lookup for both generations of embedded photography. */
if (typeof CARELINK_PHOTOS !== 'undefined') {
  Object.keys(CARELINK_PORTAL_PHOTOS).forEach(k => {
    if (!CARELINK_PHOTOS[k]) CARELINK_PHOTOS[k] = CARELINK_PORTAL_PHOTOS[k];
  });
}
if (typeof CARELINK_PHOTO_META !== 'undefined') {
  Object.keys(CARELINK_PORTAL_PHOTO_META).forEach(k => {
    if (!CARELINK_PHOTO_META[k]) CARELINK_PHOTO_META[k] = CARELINK_PORTAL_PHOTO_META[k];
  });
}
""" % (
        ",\n".join(f'  "{k}": "{v}"' for k, v in photos.items()),
        ",\n".join(f'  "{k}": {json.dumps(v)}' for k, v in meta.items()),
    )
    OUT_JS.write_text(js, encoding="utf-8")
    total = sum(m["kb"] for m in meta.values())
    print(f"[portal media] {len(photos)} images, {total:.1f} KB -> {OUT_JS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
