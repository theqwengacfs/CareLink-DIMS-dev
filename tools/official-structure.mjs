/* Generate the server-owned commissioning structure from the same source used
   by the app. No credentials or runtime data are included. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function generateOfficialStructure() {
  const data = fs.readFileSync(path.join(root, 'v6/src/data.js'), 'utf8');
  const data6 = fs.readFileSync(path.join(root, 'v6/src/data6.js'), 'utf8');
  const result = vm.runInNewContext(data + '\n' + data6 + `\nJSON.stringify({
    roster:OFFICIAL_ROSTER.map(r=>({...r,reportsTo:officialReportsTo(r)})),
    roles:ROLES, counties:COUNTIES, departments:DEPARTMENTS, exec:EXEC_DEFAULT
  })`, {}, { timeout: 3000 });
  fs.writeFileSync(path.join(root, 'api/official-structure.mjs'),
    '/* Generated by tools/official-structure.mjs; do not edit. */\nexport default ' + JSON.stringify(JSON.parse(result), null, 2) + ';\n');
}
